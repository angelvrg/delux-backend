-- 1. Tabla de Materiales (Catálogo de placas de mármol y piedra)
CREATE TABLE IF NOT EXISTS public.materiales (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre text NOT NULL,
    descripcion text,
    foto_url text NOT NULL,
    largo numeric(6, 2) NOT NULL,
    ancho numeric(6, 2) NOT NULL,
    espesor numeric(4, 2) NOT NULL,
    precio_m2 numeric(10, 2) NOT NULL,
    creado_en timestamp with time zone DEFAULT now()
);

-- 2. Tabla de Cotizaciones (Solicitudes de clientes)
CREATE TABLE IF NOT EXISTS public.cotizaciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id bigint REFERENCES public.materiales(id) ON DELETE CASCADE,
    nombre_cliente text NOT NULL,
    telefono_cliente text NOT NULL,
    metros_cuadrados numeric(8, 2) NOT NULL,
    precio_m2_registrado numeric(10, 2) NOT NULL,
    total_estimado numeric(12, 2) NOT NULL,
    mensaje text,
    estado text DEFAULT 'Pendiente',
    creado_en timestamp with time zone DEFAULT now()
);

-- Índices para optimizar búsquedas frecuentes
CREATE INDEX IF NOT EXISTS idx_materiales_nombre ON public.materiales(nombre);
CREATE INDEX IF NOT EXISTS idx_cotizaciones_material_id ON public.cotizaciones(material_id);
CREATE INDEX IF NOT EXISTS idx_cotizaciones_creado_en ON public.cotizaciones(creado_en DESC);

-- Habilitar Row Level Security (RLS) pero permitir acceso público de lectura/escritura en el caso de demostración
ALTER TABLE public.materiales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cotizaciones ENABLE ROW LEVEL SECURITY;

-- Políticas de acceso para API pública
CREATE POLICY "Permitir lectura publica de materiales"
    ON public.materiales FOR SELECT USING (true);

CREATE POLICY "Permitir insercion de materiales"
    ON public.materiales FOR INSERT WITH CHECK (true);

CREATE POLICY "Permitir lectura de cotizaciones"
    ON public.cotizaciones FOR SELECT USING (true);

CREATE POLICY "Permitir insercion de cotizaciones"
    ON public.cotizaciones FOR INSERT WITH CHECK (true);

